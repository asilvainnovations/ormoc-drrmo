#!/usr/bin/env python3
"""Validation Task Locator -> supabase/seed/operational/11_validation_locator.sql (1.34.0, B = MAP).

Reads the "Validation Task Locator" sheet of reference/Validation_Tracker_Ormoc_MODE.xlsx and writes, for each VR item,
what the lead office needs to act (Ability): chapter version, issue type, exact section, SOP or workflow, table or form,
printed pages, the task, supporting offices, evidence expected, closure criterion, and whether the item needs the
competent authority's decision before it can close. Fields already filled in MODE are kept.
Run: python3 scripts/validation_locator_seed.py
"""
import re
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'reference' / 'Validation_Tracker_Ormoc_MODE.xlsx'
OUT = ROOT / 'supabase' / 'seed' / 'operational' / '11_validation_locator.sql'
AUTHORITY = re.compile(r'legal|authority|decision required|decision/|management decision|institutional', re.I)
PLACEHOLDER = re.compile(r'^(See exact reference|As specified in the relevant decision)', re.I)


def q(v):
    if v is None:
        return 'null'
    s = re.sub(r'\s+', ' ', str(v).replace('\xa0', ' ')).strip()
    if not s or PLACEHOLDER.match(s):
        return 'null'
    return "'" + s.replace("'", "''") + "'"


def main():
    rows = list(openpyxl.load_workbook(SRC, read_only=True)['Validation Task Locator'].iter_rows(values_only=True))
    head = next(i for i, r in enumerate(rows) if r and r[0] == 'Locator ID')
    items = [r for r in rows[head + 1:] if len(r) > 14 and r[1] and str(r[1]).startswith('VR-')]
    if len(items) != len({r[1] for r in items}):
        sys.exit('Duplicate Tracker IDs in the locator sheet.')
    values = []
    for r in items:
        values.append('  (' + ', '.join([
            q(r[1]), q(r[4]), q(r[5]), q(r[6]), q(r[7]), q(r[8]), q(r[9]), q(r[10]), q(r[12]), q(r[13]), q(r[14]),
            'true' if AUTHORITY.search(str(r[5] or '')) else 'false']) + ')')
    sql = f"""-- Validation Task Locator ({len(items)} items) from reference/Validation_Tracker_Ormoc_MODE.xlsx. Generated by
-- scripts/validation_locator_seed.py; do not edit by hand. 1.34.0 (B = MAP): gives each validation task the exact section,
-- SOP, table or form, printed pages, the task, evidence expected and closure criterion, so the lead office can act
-- without hunting for them. Fields already filled in MODE are kept. Needs migration 20261128004100. Safe to run again.
begin;

update public.manual_review_items m set
  chapter_version   = coalesce(m.chapter_version, v.chapter_version),
  issue_type        = coalesce(m.issue_type, v.issue_type),
  section_ref       = coalesce(nullif(m.section_ref, ''), v.section_ref),
  sop_ref           = coalesce(m.sop_ref, v.sop_ref),
  artefact_ref      = coalesce(m.artefact_ref, v.artefact_ref),
  printed_pages     = coalesce(m.printed_pages, v.printed_pages),
  task              = coalesce(m.task, v.task),
  supporting_offices = coalesce(m.supporting_offices, v.supporting_offices),
  evidence_expected = coalesce(m.evidence_expected, v.evidence_expected),
  closure_criterion = coalesce(m.closure_criterion, v.closure_criterion),
  needs_authority   = m.needs_authority or v.needs_authority
from (values
{(','+chr(10)).join(values)}
) as v(source_tracker_id, chapter_version, issue_type, section_ref, sop_ref, artefact_ref, printed_pages, task,
       supporting_offices, evidence_expected, closure_criterion, needs_authority)
where m.source_tracker_id = v.source_tracker_id;

commit;
"""
    OUT.write_text(sql, encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: {len(items)} items')


if __name__ == '__main__':
    main()
