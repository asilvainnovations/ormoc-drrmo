// Parity: deriveStatus must agree with app.eoc_assessment_status in
// supabase/migrations/20261114003000_eoc_assessment.sql (ADR-005), and the generated seed part
// must carry the full accomplished checklist (154 items, one draft run, 154 responses).
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { deriveStatus, statusCounts, STATUS_ORDER } from './eoc_assessment';
import type { EocAssessmentStatus } from '@/types';

// The rule as the SQL function states it, written out case by case so a drift in either
// direction fails here. [scores, expected status]
const SQL_CASES: [ReadonlyArray<number | null>, EocAssessmentStatus][] = [
  [[], 'no_direct_indicator'],
  [[null], 'no_direct_indicator'],
  [[null, null], 'no_direct_indicator'],
  [[4], 'met'],
  [[3], 'met'],
  [[4, 3, 4], 'met'],
  [[2], 'partially_met'],
  [[4, 2], 'partially_met'],
  [[3, 4, 2, 4], 'partially_met'],
  [[1], 'largely_unmet'],
  [[3, 1, 4], 'largely_unmet'],
  [[0], 'not_met'],
  [[4, 0, 3], 'not_met'],
  [[0, 1, 2, 3, 4], 'not_met'],
  [[null, 3], 'met'],          // NA scores are ignored
  [[null, 2], 'partially_met'],
  [[2, null, 0], 'not_met'],
];

describe('deriveStatus — parity with app.eoc_assessment_status', () => {
  it.each(SQL_CASES)('scores %j -> %s', (scores, expected) => {
    expect(deriveStatus(scores)).toBe(expected);
  });

  it('agrees with the SQL case ladder for every score array up to length 3 over {null,0,1,2,3,4}', () => {
    const values: (number | null)[] = [null, 0, 1, 2, 3, 4];
    const sqlRule = (scores: (number | null)[]): EocAssessmentStatus => {
      const present = scores.filter((s): s is number => s !== null);
      if (present.length === 0) return 'no_direct_indicator';
      const min = Math.min(...present);
      return min >= 3 ? 'met' : min === 2 ? 'partially_met' : min === 1 ? 'largely_unmet' : 'not_met';
    };
    const arrays: (number | null)[][] = [[]];
    for (let len = 1; len <= 3; len++) {
      for (const prev of arrays.filter((a) => a.length === len - 1)) {
        for (const v of values) arrays.push([...prev, v]);
      }
    }
    for (const a of arrays) expect(deriveStatus(a)).toBe(sqlRule(a));
  });
});

describe('statusCounts', () => {
  it('counts every status, keeping the zeros', () => {
    expect(statusCounts(['met', 'met', 'not_met'])).toEqual({ met: 2, partially_met: 0, largely_unmet: 0, not_met: 1, not_applicable: 0, not_assessed: 0, no_direct_indicator: 0 });
    expect(STATUS_ORDER).toEqual(['met', 'partially_met', 'largely_unmet', 'not_met', 'not_applicable', 'not_assessed', 'no_direct_indicator']);
  });
});

// The seed part is the SQL deliverable of this module; these counts are also asserted in the
// database (supabase/tests/10_rules_and_security.sql) after it loads.
describe('seed parts 38a-38c (generated by scripts/eoc_assessment_seed.py)', () => {
  // Split under the SQL editor limit: 38a holds the items and the run, 38b and 38c the answers.
  const files = ['38a', '38b', '38c'].map((p) => readFileSync(`supabase/seed/parts/${p}_eoc_assessment.sql`, 'utf8'));
  const seed = files.join('\n');
  // Count tuples (a tuple always starts with its id); response tuples carry three uuids.
  const ids = (block: string) => (block.match(/(?:^|,)\('[0-9a-f-]{36}'::uuid/g) ?? []).length;
  const block = (re: RegExp): string => {
    const m = re.exec(seed);
    if (!m || m[1] === undefined) throw new Error(`seed part 38 does not match ${re}`);
    return m[1];
  };

  const answerBlocks = () => files.slice(1).map((f) => {
    const m = /insert into public\.eoc_assessment_responses[\s\S]*?from \(values\n([\s\S]*?)\n  \) as v/.exec(f);
    if (!m || m[1] === undefined) throw new Error('an answer part does not match');
    return m[1];
  }).join(',');

  it('seeds 154 items, exactly one draft run and 154 pre-filled primary-EOC answers', () => {
    expect(ids(block(/insert into public\.eoc_assessment_items [^;]*values\n([\s\S]*?)\non conflict/))).toBe(154);
    expect(ids(answerBlocks())).toBe(154);
    expect(seed).toContain("'IAT v1-7 (Oct 2026)','draft'");
    expect(seed).not.toContain("'validated'");
    for (const f of files.slice(1)) expect(f).toContain("'primary', v.status, 'prefilled_iat'");
  });

  it('keeps every part under the SQL editor limit', () => {
    for (const f of files) expect(new TextEncoder().encode(f).length).toBeLessThan(100_000);
  });

  it('keeps the workbook status distribution', () => {
    const responses = answerBlocks();
    const tally: Record<string, number> = {};
    for (const m of responses.matchAll(/::uuid,'(met|partially_met|largely_unmet|not_met|no_direct_indicator)'/g)) {
      const key = m[1]!;
      tally[key] = (tally[key] ?? 0) + 1;
    }
    expect(tally).toEqual({ met: 59, partially_met: 45, largely_unmet: 36, not_met: 8, no_direct_indicator: 6 });
  });
});
